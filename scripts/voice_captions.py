def compositional(rng: random.Random) -> str:
    who = rng.choice(GENDER_AGE)
    quality = rng.choice(QUALITY)
    pattern = rng.randrange(4)
    if pattern == 0:
        caption = f"{quality}声の{who}。{rng.choice(EMOTION)}{rng.choice(STYLE)}。"
    elif pattern == 1:
        caption = f"{who}の{quality}声。{rng.choice(CONTEXT)}、{rng.choice(EMOTION)}{rng.choice(STYLE)}。"
    elif pattern == 2:
        caption = f"{quality}声の{who}"
    else:
        caption = f"{who}。{rng.choice(CONTEXT)}{rng.choice(STYLE)}。"
    return (caption + rng.choice(ACOUSTIC)).strip()


def voice_captions(n: int, seed: int = 0) -> list[str]:
    rng = random.Random(seed)
    captions = list(dict.fromkeys(HANDWRITTEN))
    seen = set(captions)
    attempts = 0
    while len(captions) < n and attempts < n * 20:
        attempts += 1
        caption = compositional(rng)
        if caption not in seen:
            seen.add(caption)
            captions.append(caption)
    rng.shuffle(captions)
    return captions[:n]
